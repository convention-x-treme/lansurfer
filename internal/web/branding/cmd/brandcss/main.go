package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/convention-x-treme/lansurfer/internal/web/branding"
)

var output = flag.String("output", "", "generated stylesheet path")

func main() {
	flag.Parse()
	if strings.TrimSpace(*output) == "" {
		fmt.Fprintln(os.Stderr, "-output is required")
		os.Exit(2)
	}

	var rendered bytes.Buffer
	if err := stylesheet.Execute(&rendered, branding.Default()); err != nil {
		fmt.Fprintf(os.Stderr, "render brand stylesheet: %v\n", err)
		os.Exit(1)
	}

	// Keep output deterministic and end it with exactly one newline.
	content := bytes.TrimSpace(rendered.Bytes())
	content = append(content, '\n')
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "create output directory: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, content, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write brand stylesheet: %v\n", err)
		os.Exit(1)
	}
}

